-- V160 — L'ouverture anticipée des plis de l'appel d'offres restreint (demande front du 2026-11-02 `demande-backend-2026-11-02-
-- appel-offres-restreint.md`, §B7 ; arbitrage Q4 du pilote : l'outiller ; loi n° 2016-055, art. 38-VI ; décret n° 2019-1310, art. 14 ;
-- guide de la CAO, § 4.5.1).
--
-- 1. t_ouverture_anticipee : une demande par procédure — DEMANDEE (consentements attendus), ACCORDEE (tous ont consenti), FIXEE (la
--    PRMP a fixé la nouvelle date d'ouverture), REFUSEE (un invité a refusé : la date initiale demeure, la demande est close).
-- 2. t_consentement_anticipation : la réponse écrite de chaque invité qui a déposé (accord ou refus, horodatée, nominative).
-- Idempotente.
-- ═══════════════════════════════════════════════════════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS public.t_ouverture_anticipee (
    "ID_DMC"              bigint NOT NULL,
    "ETAT"                character varying(10) NOT NULL,
    "OUVERTURE_INITIALE"  timestamp without time zone,
    "NOUVELLE_OUVERTURE"  timestamp without time zone,
    "DEMANDEE_LE"         timestamp without time zone NOT NULL,
    "DEMANDEE_PAR"        character varying(100),
    "FIXEE_LE"            timestamp without time zone,
    "FIXEE_PAR"           character varying(100),
    CONSTRAINT t_ouverture_anticipee_pkey PRIMARY KEY ("ID_DMC"),
    CONSTRAINT ck_ouverture_anticipee_etat CHECK ("ETAT" IN ('DEMANDEE', 'ACCORDEE', 'FIXEE', 'REFUSEE'))
);

CREATE TABLE IF NOT EXISTS public.t_consentement_anticipation (
    "ID"           bigint GENERATED BY DEFAULT AS IDENTITY,
    "ID_DMC"       bigint NOT NULL,
    "ID_CANDIDAT"  character varying(10) NOT NULL,
    "NOM"          character varying(255),
    "ACCORD"       boolean,
    "REPONDU_LE"   timestamp without time zone,
    "REPONDU_PAR"  character varying(100),
    CONSTRAINT t_consentement_anticipation_pkey PRIMARY KEY ("ID"),
    CONSTRAINT fk_consentement_anticipation FOREIGN KEY ("ID_DMC") REFERENCES public.t_ouverture_anticipee ("ID_DMC") ON DELETE CASCADE,
    CONSTRAINT uk_consentement_anticipation UNIQUE ("ID_DMC", "ID_CANDIDAT")
);
