-- ═══════════════════════════════════════════════════════════════════════════════════════════════
-- V78 — L'évaluation des offres, tranche 1d (demande front du 2026-10-07, §B6) : le rapport d'évaluation.
--
-- 1. Le rapport d'une procédure : produit par le responsable quand toutes les étapes de tous les lots sont arrêtées, en PDF et en
--    Word ; les signataires appelés (membres de la CAO, hors ceux qui ont déclaré un conflit) ; la date de la dernière signature.
-- 2. Les signatures du rapport : signature électronique simple d'un membre, avec son observation éventuelle (désaccord), ou
--    empêchement constaté par le président (motif), sur le modèle du PV d'ouverture (V70).
-- Idempotente.
-- ═══════════════════════════════════════════════════════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS public.t_evaluation_rapport (
    "ID_DMC"        bigint NOT NULL,
    "PRODUIT_LE"    timestamp without time zone NOT NULL,
    "PRODUIT_PAR"   character varying(100),
    "OBSERVATIONS"  text,
    "SIGNATAIRES"   character varying(400),
    "PDF"           bytea,
    "DOCX"          bytea,
    "SIGNE_LE"      timestamp without time zone,
    CONSTRAINT t_evaluation_rapport_pkey PRIMARY KEY ("ID_DMC")
);

CREATE TABLE IF NOT EXISTS public.t_evaluation_signature (
    "ID"            bigint GENERATED BY DEFAULT AS IDENTITY,
    "ID_DMC"        bigint NOT NULL,
    "IM"            character varying(20) NOT NULL,
    "DATE"          timestamp without time zone NOT NULL,
    "EMPECHEMENT"   boolean NOT NULL DEFAULT false,
    "MOTIF"         text,
    "CONSTATE_PAR"  character varying(100),
    "OBSERVATION"   text,
    CONSTRAINT t_evaluation_signature_pkey PRIMARY KEY ("ID"),
    CONSTRAINT uq_evaluation_signature UNIQUE ("ID_DMC", "IM")
);
