INSERT INTO public.t_type_piece_jointe ("ID_TYPE_PIECE", "ID_TYPE_DOSSIER", "LIBELLE_PIECE", "OBLIGATOIRE", "ORDRE", "CODE")
SELECT base.m + lib.n, NULL, lib.libelle, false, NULL, lib.code
FROM base, lib
WHERE NOT EXISTS (SELECT 1 FROM public.t_type_piece_jointe t WHERE t."CODE" = lib.code);

