-- V95 — Le référentiel du contrôle aligné sur le Manuel de contrôle a priori, tranche M2 : les pièces exigées PAR SOUS-TYPE (demande
-- front du 2026-10-08 `demande-backend-2026-10-08-manuel-controle-a-priori.md`, §B2 ; arbitrages du pilote du 08/10 : les pièces « * »
-- du manuel exigées dès M2 ; les plans PPM / PPM-AGPM inchangés ; sans fiche, les pièces qui dépendent de la catégorie sont servies
-- sans obligation).
--
-- 1. t_piece_sous_type : l'association d'un type de pièce à un sous-type — obligation, ordre, et condition sur la CATEGORIE de la fiche
--    (FOURNITURES_SERVICES, TRAVAUX, PRESTATIONS_INTELLECTUELLES) et sur la FORME (CONTRAT_CADRE ; AUTRE = toute autre forme). Un
--    sous-type qui a une liste n'utilise qu'elle ; les autres gardent les pièces de leur famille (comportement d'avant).
-- 2. La bibliothèque des pièces du manuel (types sans famille : ID_TYPE_DOSSIER nul, servis par leurs associations), codes stables ;
--    identifiants explicites (MAX + rang) puis recalage de la séquence (cf. V83).
-- 3. Les listes du manuel, sous-type par sous-type ; les pièces que l'application joint d'office y sont reprises par leur code
--    (DAO_COMPLET, RAPPORT_PRESELECTION, PROJET_MARCHE, CAHIER_CHARGES, DEVIS_ESTIMATIF, PV_OUVERTURE, RAPPORT_ANALYSE,
--    MOTIFS_SANS_SUITE). Les associations ne s'écrivent que pour les sous-types présents au référentiel.
-- Idempotente.
-- ═══════════════════════════════════════════════════════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS public.t_piece_sous_type (
    "ID"             bigint GENERATED BY DEFAULT AS IDENTITY,
    "ID_TYPE_PIECE"  integer NOT NULL REFERENCES public.t_type_piece_jointe ("ID_TYPE_PIECE"),
    "ID_SOUS_TYPE"   character varying(20) NOT NULL REFERENCES public.tr_sous_type_dossier ("ID_SOUS_TYPE"),
    "OBLIGATOIRE"    boolean NOT NULL,
    "ORDRE"          integer NOT NULL,
    "CATEGORIE"      character varying(40),
    "FORME"          character varying(20),
    CONSTRAINT t_piece_sous_type_pkey PRIMARY KEY ("ID"),
    CONSTRAINT ck_piece_sous_type_forme CHECK ("FORME" IS NULL OR "FORME" IN ('CONTRAT_CADRE', 'AUTRE'))
);
CREATE INDEX IF NOT EXISTS ix_piece_sous_type ON public.t_piece_sous_type ("ID_SOUS_TYPE", "ORDRE");
CREATE UNIQUE INDEX IF NOT EXISTS uk_piece_sous_type ON public.t_piece_sous_type
    ("ID_TYPE_PIECE", "ID_SOUS_TYPE", COALESCE("CATEGORIE", ''), COALESCE("FORME", ''));

