-- V112 — ⚠️ 2026-10-14 : manuel révisé pour l'application, lot 2, tranche R9b (§B4, bloquant de la loi
-- n° 4, art. 44 : aucun dépôt après la date et l'heure limites ; le rejet est horodaté et tracé).
--
-- t_offre_tentative : chaque refus DELAI_DEPASSE d'un geste de dépôt (création de l'offre, envoi d'un
-- morceau, scellement), horodaté par le serveur, avec le candidat, son entreprise si elle est déclarée,
-- le lot et l'offre en cours s'ils sont connus. Écrite dans sa propre transaction : le refus annule le
-- geste, pas sa trace. Un seul enregistrement par offre et par geste MORCEAU (un client qui renvoie
-- ses morceaux ne multiplie pas les lignes). Servie au registre des dépôts et au PV d'ouverture.
-- Idempotente.
-- ═══════════════════════════════════════════════════════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS public.t_offre_tentative (
    "ID"              bigint GENERATED BY DEFAULT AS IDENTITY,
    "ID_DMC"          bigint NOT NULL,
    "ID_CANDIDAT"     character varying(10) NOT NULL,
    "ID_ENTREPRISE"   integer,
    "NIF"             character varying(50),
    "RAISON_SOCIALE"  character varying(255),
    "LOT"             integer,
    "ENVELOPPE"       character varying(12),
    "ID_OFFRE"        character varying(36),
    "GESTE"           character varying(12) NOT NULL,
    "MOTIF"           character varying(30) NOT NULL,
    "HORODATAGE"      timestamp without time zone NOT NULL,
    "DATE_LIMITE"     timestamp without time zone,
    CONSTRAINT t_offre_tentative_pkey PRIMARY KEY ("ID"),
    CONSTRAINT ck_offre_tentative_geste CHECK ("GESTE" IN ('CREATION', 'MORCEAU', 'SCELLEMENT'))
);
CREATE INDEX IF NOT EXISTS idx_offre_tentative_dmc ON public.t_offre_tentative ("ID_DMC", "HORODATAGE");
COMMENT ON TABLE public.t_offre_tentative IS 'Tentatives de depot refusees hors delai (art. 44), horodatees par le serveur — V112';
