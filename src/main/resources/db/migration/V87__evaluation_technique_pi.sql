-- V87 — Évaluation des offres, lot 3 (prestations intellectuelles), tranche PI-c (demande front du 2026-10-07,
-- `demande-backend-2026-10-07-evaluation-pi.md`, §B4 ; arbitrages du pilote : chaque membre note puis moyenne (Q4), un écart de
-- 20 % du maximum entre membres est signalé, sous-critères de la fiche (Q3)).
--
-- 1. Les notes techniques : chaque membre de la commission (déclaré sans conflit) note chaque proposition technique retenue à
--    l'examen préliminaire, élément par élément de la grille — un sous-critère de la fiche, ou un critère B06-TP-0x noté globalement
--    s'il n'a pas de sous-critère —, de 0 au maximum de l'élément, avec un motif. Une note saisie remplace la précédente du même
--    membre (le journal garde chaque saisie).
-- 2. L'arrêt de l'étape technique, par lot, par le président (et sa réouverture motivée) : la note technique de chaque proposition
--    (somme des moyennes) est alors figée, et les propositions sous le score minimum (B06-TP-07) sont éliminées.
-- 3. Le seuil d'écart entre membres, administrable : EVALUATION_ECART_NOTES_POURCENT = 20.
-- Idempotente.
-- ═══════════════════════════════════════════════════════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS public.t_evaluation_note_technique (
    "ID"         bigint GENERATED BY DEFAULT AS IDENTITY,
    "ID_DMC"     bigint NOT NULL,
    "ID_OFFRE"   character varying(36) NOT NULL,
    "IM"         character varying(20) NOT NULL,
    "ELEMENT"    character varying(30) NOT NULL,
    "NOTE"       numeric(7,2) NOT NULL,
    "MOTIF"      text NOT NULL,
    "LE"         timestamp without time zone NOT NULL,
    CONSTRAINT t_evaluation_note_technique_pkey PRIMARY KEY ("ID"),
    CONSTRAINT uq_evaluation_note_technique UNIQUE ("ID_OFFRE", "IM", "ELEMENT")
);
CREATE INDEX IF NOT EXISTS ix_evaluation_note_technique_dmc ON public.t_evaluation_note_technique ("ID_DMC");

CREATE TABLE IF NOT EXISTS public.t_evaluation_technique (
    "ID_DMC"             bigint NOT NULL,
    "LOT"                integer NOT NULL,
    "ARRETEE_LE"         timestamp without time zone,
    "ARRETEE_PAR"        character varying(100),
    "OBSERVATION"        text,
    "ROUVERTE_LE"        timestamp without time zone,
    "MOTIF_REOUVERTURE"  text,
    CONSTRAINT t_evaluation_technique_pkey PRIMARY KEY ("ID_DMC", "LOT")
);

INSERT INTO public.t_parametre ("CLE", "VALEUR", "DATE_MAJ") VALUES ('EVALUATION_ECART_NOTES_POURCENT', '20', now())
ON CONFLICT ("CLE") DO NOTHING;
