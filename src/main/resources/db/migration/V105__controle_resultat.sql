-- Un résultat de contrôle par (dossier, n° de soumission, règle) : la référence du manuel (section,
-- page, Pn) ou le point de grille, les valeurs constatées (JSON), le résultat (CONFORME, NON_CONFORME,
-- NON_APPLICABLE), le caractère bloquant, l'auteur (SERVEUR pour un contrôle automatique, le matricule
-- pour un contrôle B du Membre), la date et l'observation (obligatoire quand un contrôleur constate une
-- non-conformité). Les contrôles bloquants se jouent AVANT la soumission (400) ; les autres sont
-- enregistrés après, et rejoués à chaque resoumission. Supprimé avec le dossier.
-- Idempotente.
-- ═══════════════════════════════════════════════════════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS public.t_controle_resultat (
    "ID_CONTROLE"        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ID_DOSSIER"         integer NOT NULL REFERENCES public.t_dossier ("ID_DOSSIER") ON DELETE CASCADE,
    "NUMERO_SOUMISSION"  integer NOT NULL,
    "REFERENCE"          varchar(60),
    "ID_POINT_CTRL"      integer REFERENCES public.tr_points_ctrl ("ID_POINT_CTRL"),
    "REGLE"              varchar(60) NOT NULL,
    "LIBELLE"            varchar(300),
    "VALEURS"            text,
    "RESULTAT"           varchar(20) NOT NULL,
    "BLOQUANT"           boolean NOT NULL DEFAULT false,
    "AUTEUR"             varchar(100) NOT NULL,
    "DATE_CONTROLE"      timestamp NOT NULL,
    "OBSERVATION"        text,
    CONSTRAINT ck_controle_resultat_resultat CHECK ("RESULTAT" IN ('CONFORME', 'NON_CONFORME', 'NON_APPLICABLE'))
);

CREATE INDEX IF NOT EXISTS ix_controle_resultat_dossier ON public.t_controle_resultat ("ID_DOSSIER", "NUMERO_SOUMISSION");
