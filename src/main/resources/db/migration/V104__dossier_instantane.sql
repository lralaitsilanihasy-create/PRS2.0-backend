-- voit — l'instantané à la soumission).
--
-- À la soumission d'un dossier (et à chaque resoumission), le serveur fige, écran par écran, le JSON du
-- DTO de lecture tel qu'il est servi à cet instant : SEANCE, EVALUATION, AMI, ATTRIBUTION, CAO, AVIS, PLAN,
-- ACTE, DSS. Une ligne par (dossier, n° de soumission, écran), immuable (même fonction que les versions
-- archivées, V18 : aucune mise à jour admise ; la suppression suit celle du dossier). Les profils CNM lisent
-- ces instantanés à la place des pièces retirées (R2).
-- Idempotente.
-- ═══════════════════════════════════════════════════════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS public.t_dossier_instantane (
    "ID_INSTANTANE"      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ID_DOSSIER"         integer NOT NULL REFERENCES public.t_dossier ("ID_DOSSIER") ON DELETE CASCADE,
    "NUMERO_SOUMISSION"  integer NOT NULL,
    "ECRAN"              varchar(20) NOT NULL,
    "CONTENU"            text NOT NULL,
    "EMPREINTE"          varchar(64) NOT NULL,
    "FIGE_LE"            timestamp NOT NULL,
    "FIGE_PAR"           varchar(100),
    CONSTRAINT uq_dossier_instantane UNIQUE ("ID_DOSSIER", "NUMERO_SOUMISSION", "ECRAN"),
    CONSTRAINT ck_dossier_instantane_ecran
        CHECK ("ECRAN" IN ('SEANCE', 'EVALUATION', 'AMI', 'ATTRIBUTION', 'CAO', 'AVIS', 'PLAN', 'ACTE', 'DSS'))
);

CREATE INDEX IF NOT EXISTS ix_dossier_instantane_dossier ON public.t_dossier_instantane ("ID_DOSSIER");

DROP TRIGGER IF EXISTS trg_dossier_instantane_immuable ON public.t_dossier_instantane;
CREATE TRIGGER trg_dossier_instantane_immuable
    BEFORE UPDATE ON public.t_dossier_instantane
    FOR EACH ROW EXECUTE FUNCTION public.fn_version_archivee_immuable();
