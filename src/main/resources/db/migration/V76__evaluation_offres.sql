-- V76 — L'évaluation des offres, lot 1, tranche 1a (demande front du 2026-10-07, §B1, §B2, §B7 ; arbitrages du pilote du
-- 07/10 : tout membre saisit, le président arrête ; la CAO décide toujours, les alertes de séance pré-remplissent).
--
-- 1. L'évaluation d'une procédure, ouverte par le responsable une fois le PV d'ouverture signé (séance CLOSE).
-- 2. La déclaration préalable de chaque membre de la CAO (absence de conflit d'intérêts, confidentialité ; art. 21-d, 12-V).
-- 3. Les arrêts d'étape, par lot : arrêter fige ; rouvrir (motif) rouvre aussi les étapes suivantes. Rien ne s'efface : un arrêt
--    rouvert garde sa date et reçoit celle de sa réouverture.
-- 4. Les décisions sur les offres, par étape, en ajout seul : une décision corrigée est marquée remplacée, jamais effacée (P3).
-- 5. Les demandes adressées aux candidats (précisions, art. 35-VI ; justifications, art. 48) et leurs réponses.
-- 6. Le journal de l'évaluation.
-- Idempotente.
-- ═══════════════════════════════════════════════════════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS public.t_evaluation (
    "ID_DMC"       bigint NOT NULL,
    "ETAT"         character varying(20) NOT NULL,
    "OUVERTE_LE"   timestamp without time zone NOT NULL,
    "OUVERTE_PAR"  character varying(100),
    CONSTRAINT t_evaluation_pkey PRIMARY KEY ("ID_DMC"),
    CONSTRAINT ck_evaluation_etat CHECK ("ETAT" IN ('EN_COURS', 'RAPPORT_A_SIGNER', 'CLOSE'))
);

CREATE TABLE IF NOT EXISTS public.t_evaluation_declaration (
    "ID"         bigint GENERATED BY DEFAULT AS IDENTITY,
    "ID_DMC"     bigint NOT NULL,
    "IM"         character varying(20) NOT NULL,
    "SIGNEE_LE"  timestamp without time zone NOT NULL,
    "CONFLIT"    boolean NOT NULL DEFAULT false,
    "PRECISION"  text,
    CONSTRAINT t_evaluation_declaration_pkey PRIMARY KEY ("ID"),
    CONSTRAINT uq_evaluation_declaration UNIQUE ("ID_DMC", "IM")
);

CREATE TABLE IF NOT EXISTS public.t_evaluation_etape (
    "ID"                 bigint GENERATED BY DEFAULT AS IDENTITY,
    "ID_DMC"             bigint NOT NULL,
    "LOT"                integer NOT NULL,
    "ETAPE"              character varying(20) NOT NULL,
    "ARRETEE_LE"         timestamp without time zone NOT NULL,
    "ARRETEE_PAR"        character varying(20) NOT NULL,
    "OBSERVATION"        text,
    "ROUVERTE_LE"        timestamp without time zone,
    "ROUVERTE_PAR"       character varying(20),
    "MOTIF_REOUVERTURE"  text,
    CONSTRAINT t_evaluation_etape_pkey PRIMARY KEY ("ID"),
    CONSTRAINT ck_evaluation_etape CHECK ("ETAPE" IN ('CONFORMITE', 'EVALUATION', 'ANORMALES', 'QUALIFICATION'))
);
-- Un seul arrêt en vigueur par lot et par étape.
CREATE UNIQUE INDEX IF NOT EXISTS uq_evaluation_etape_en_vigueur
    ON public.t_evaluation_etape ("ID_DMC", "LOT", "ETAPE") WHERE "ROUVERTE_LE" IS NULL;

CREATE TABLE IF NOT EXISTS public.t_evaluation_decision (
    "ID"             bigint GENERATED BY DEFAULT AS IDENTITY,
    "ID_DMC"         bigint NOT NULL,
    "ID_OFFRE"       character varying(36) NOT NULL,
    "LOT"            integer NOT NULL,
    "ETAPE"          character varying(20) NOT NULL,
    "DECISION"       character varying(20) NOT NULL,
    "QUALIFICATION"  character varying(20),
    "MOTIF"          text,
    "CLAUSE"         character varying(300),
    "CONTENU"        text,
    "PAR"            character varying(20) NOT NULL,
    "LE"             timestamp without time zone NOT NULL,
    "REMPLACEE_LE"   timestamp without time zone,
    CONSTRAINT t_evaluation_decision_pkey PRIMARY KEY ("ID"),
    CONSTRAINT ck_evaluation_decision_etape CHECK ("ETAPE" IN ('CONFORMITE', 'EVALUATION', 'ANORMALES', 'QUALIFICATION')),
    CONSTRAINT ck_evaluation_decision_qualification CHECK ("QUALIFICATION" IS NULL
        OR "QUALIFICATION" IN ('IRRECEVABLE', 'NON_CONFORME', 'INAPPROPRIEE', 'INACCEPTABLE'))
);
-- Une seule décision en vigueur par offre et par étape ; les remplacées restent.
CREATE UNIQUE INDEX IF NOT EXISTS uq_evaluation_decision_en_vigueur
    ON public.t_evaluation_decision ("ID_OFFRE", "ETAPE") WHERE "REMPLACEE_LE" IS NULL;
CREATE INDEX IF NOT EXISTS ix_evaluation_decision_dmc ON public.t_evaluation_decision ("ID_DMC");

CREATE TABLE IF NOT EXISTS public.t_evaluation_demande (
    "ID"               bigint GENERATED BY DEFAULT AS IDENTITY,
    "ID_DMC"           bigint NOT NULL,
    "ID_OFFRE"         character varying(36) NOT NULL,
    "TYPE"             character varying(15) NOT NULL,
    "QUESTION"         text NOT NULL,
    "DELAI_JOURS"      integer NOT NULL,
    "ECHEANCE"         timestamp without time zone NOT NULL,
    "DEMANDEE_LE"      timestamp without time zone NOT NULL,
    "DEMANDEE_PAR"     character varying(100),
    "REPONSE"          text,
    "REPONSE_NOM"      character varying(255),
    "REPONSE_FORMAT"   character varying(50),
    "REPONSE_TAILLE"   bigint,
    "REPONSE_CONTENU"  bytea,
    "REPONDUE_LE"      timestamp without time zone,
    CONSTRAINT t_evaluation_demande_pkey PRIMARY KEY ("ID"),
    CONSTRAINT ck_evaluation_demande_type CHECK ("TYPE" IN ('PRECISION', 'JUSTIFICATION'))
);
CREATE INDEX IF NOT EXISTS ix_evaluation_demande_offre ON public.t_evaluation_demande ("ID_OFFRE");

CREATE TABLE IF NOT EXISTS public.t_evaluation_journal (
    "ID"       bigint GENERATED BY DEFAULT AS IDENTITY,
    "ID_DMC"   bigint NOT NULL,
    "DATE"     timestamp without time zone NOT NULL,
    "ACTEUR"   character varying(100),
    "ACTION"   character varying(30) NOT NULL,
    "DETAIL"   text,
    CONSTRAINT t_evaluation_journal_pkey PRIMARY KEY ("ID")
);
CREATE INDEX IF NOT EXISTS ix_evaluation_journal_dmc ON public.t_evaluation_journal ("ID_DMC");
