-- V77 — L'évaluation des offres, tranche 1b (demande front du 2026-10-07, §B3.6 ; Q5 non tranchée : l'égalité est signalée et
-- départagée par la CAO, avec un motif).
--
-- Le départage d'offres classées à égalité de montant évalué dans un lot : l'ordre retenu (identifiants d'offres, du premier au
-- dernier) et son motif. En ajout seul, comme les décisions : un départage repris est marqué remplacé, jamais effacé.
-- Le montant évalué et les corrections vivent dans t_evaluation_decision (étape EVALUATION, CONTENU en JSON).
-- Idempotente.
-- ═══════════════════════════════════════════════════════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS public.t_evaluation_departage (
    "ID"            bigint GENERATED BY DEFAULT AS IDENTITY,
    "ID_DMC"        bigint NOT NULL,
    "LOT"           integer NOT NULL,
    "ORDRE"         character varying(400) NOT NULL,
    "MOTIF"         text NOT NULL,
    "PAR"           character varying(20) NOT NULL,
    "LE"            timestamp without time zone NOT NULL,
    "REMPLACE_LE"   timestamp without time zone,
    CONSTRAINT t_evaluation_departage_pkey PRIMARY KEY ("ID")
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_evaluation_departage_en_vigueur
    ON public.t_evaluation_departage ("ID_DMC", "LOT") WHERE "REMPLACE_LE" IS NULL;
