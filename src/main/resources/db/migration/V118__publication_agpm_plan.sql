-- ⚠️ 2026-10-15 (demande front « pièces de l'AMI et publication de l'AGPM », §B2 ; propositions du front validées par le pilote le
-- 15/10 ; arbitrages de l'utilisateur au backend le 15/10 : H1 numéro et date du journal lus sur le plan, figés ; H2 la publication
-- suit la filiation du plan) — la publication de l'AGPM (scan du journal) se dépose UNE fois, sur le plan de passation contrôlé, avec
-- le nom du journal, son numéro, la date de parution et la référence de l'AGPM. Une nouvelle publication remplace la précédente
-- (REMPLACEE_LE posé, rien n'est effacé). Chaque dossier conduit dans l'application dont la ligne relève du plan la reprend d'office
-- sous la pièce PUBLICATION_AGPM ; l'avis spécifique lit le numéro et la date du journal sur elle.

create table public.t_publication_agpm (
    "ID_PUBLICATION"  bigint generated by default as identity primary key,
    "ID_DOSSIER"      integer      not null references public.t_dossier ("ID_DOSSIER"),
    "JOURNAL"         varchar(200) not null,
    "NUMERO"          varchar(50),
    "DATE_PARUTION"   date         not null,
    "REFERENCE_AGPM"  varchar(100) not null,
    "NOM_FICHIER"     varchar(255) not null,
    "CONTENU"         bytea        not null,
    "TAILLE"          bigint       not null,
    "DEPOSE_PAR"      varchar(100),
    "DEPOSE_LE"       timestamp    not null,
    "REMPLACEE_LE"    timestamp
);

-- Une seule publication en vigueur par plan.
create unique index uk_publication_agpm_en_vigueur on public.t_publication_agpm ("ID_DOSSIER") where "REMPLACEE_LE" is null;
