-- V154 — ⚠️ 2026-10-30 : demande front « pieces-ddm-donnees », §B2 (décision du pilote sur Q1 : le journal de publication reste exigé).
--
-- La preuve de la première publication de l'avis se dépose une seule fois, sur la procédure (le DMC de la fiche), après sa
-- publication : le scan du journal (en prestations intellectuelles, les lettres d'invitation avec accusé), la date de parution (ou
-- d'envoi), le journal, le numéro. Sur le modèle de la publication de l'AGPM déposée sur le plan (V118) : une nouvelle publication
-- remplace la précédente (REMPLACEE_LE posé). Le dossier de marché né de l'attribution la reçoit comme pièce fournie
-- (PUBLICATION_AVIS), sans copie du fichier.
-- ═══════════════════════════════════════════════════════════════════════════════════════════════

create table if not exists public.t_publication_avis (
    "ID_PUBLICATION"  bigint generated by default as identity primary key,
    "ID_DMC"          bigint       not null references public.t_dossier_mec ("ID_DMC"),
    "NATURE"          varchar(20)  not null,
    "JOURNAL"         varchar(200),
    "NUMERO"          varchar(50),
    "DATE_PARUTION"   date         not null,
    "NOM_FICHIER"     varchar(255) not null,
    "CONTENU"         bytea        not null,
    "TAILLE"          bigint       not null,
    "DEPOSE_PAR"      varchar(100),
    "DEPOSE_LE"       timestamp    not null,
    "REMPLACEE_LE"    timestamp,
    constraint ck_publication_avis_nature check ("NATURE" in ('JOURNAL', 'LETTRES_INVITATION'))
);

-- Une seule publication en vigueur par procédure.
create unique index if not exists uk_publication_avis_en_vigueur on public.t_publication_avis ("ID_DMC") where "REMPLACEE_LE" is null;
