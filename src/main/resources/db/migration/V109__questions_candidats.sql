--    réponse de la PRMP (texte, fichier facultatif), diffusée à sa publication.
-- 2. Le type de pièce « Questions et réponses des candidats » (code QUESTIONS_REPONSES, famille DDM),
--    produit par le serveur et joint d'office au dossier de marché (identifiant explicite puis recalage
--    de la séquence, cf. V93).
-- Idempotente.
-- ═══════════════════════════════════════════════════════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS public.t_question_candidat (
    "ID"               bigint GENERATED BY DEFAULT AS IDENTITY,
    "ID_DMC"           bigint NOT NULL,
    "ID_CANDIDAT"      character varying(10) NOT NULL,
    "ID_ENTREPRISE"    integer,
    "QUESTION"         text NOT NULL,
    "POSEE_LE"         timestamp without time zone NOT NULL,
    "REPONSE"          text,
    "REPONSE_NOM"      character varying(255),
    "REPONSE_FORMAT"   character varying(50),
    "REPONSE_TAILLE"   bigint,
    "REPONSE_CONTENU"  bytea,
    "REPONDUE_LE"      timestamp without time zone,
    "REPONDUE_PAR"     character varying(100),
    "PUBLIEE_LE"       timestamp without time zone,
    CONSTRAINT t_question_candidat_pkey PRIMARY KEY ("ID"),
    CONSTRAINT fk_question_candidat_dmc FOREIGN KEY ("ID_DMC") REFERENCES public.t_dossier_mec ("ID_DMC") ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS ix_question_candidat_dmc ON public.t_question_candidat ("ID_DMC", "POSEE_LE");

INSERT INTO public.t_type_piece_jointe ("ID_TYPE_PIECE", "ID_TYPE_DOSSIER", "LIBELLE_PIECE", "OBLIGATOIRE", "ORDRE", "CODE")
SELECT COALESCE((SELECT MAX("ID_TYPE_PIECE") FROM public.t_type_piece_jointe), 0) + 1, 'DDM', 'Questions et réponses des candidats',
       false, 99, 'QUESTIONS_REPONSES'
WHERE NOT EXISTS (SELECT 1 FROM public.t_type_piece_jointe WHERE "CODE" = 'QUESTIONS_REPONSES')
  AND EXISTS (SELECT 1 FROM public.tr_type_dossier WHERE "ID_TYPE_DOSSIER" = 'DDM');

SELECT setval(pg_get_serial_sequence('public.t_type_piece_jointe', 'ID_TYPE_PIECE'),
              GREATEST((SELECT COALESCE(MAX("ID_TYPE_PIECE"), 0) FROM public.t_type_piece_jointe), 1));
