INSERT INTO public.t_parametre ("CLE", "VALEUR", "DATE_MAJ", "IM_ACTEUR")
SELECT 'CAO_QUORUM', 'MAJORITE', now(), NULL
WHERE NOT EXISTS (SELECT 1 FROM public.t_parametre WHERE "CLE" = 'CAO_QUORUM');

ALTER TABLE public.t_parametre_interne_procedure ADD COLUMN IF NOT EXISTS "CAO_QUORUM" character varying(20);

CREATE TABLE IF NOT EXISTS public.t_cao_representant (
    "ID" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ID_DMC" bigint NOT NULL REFERENCES public.t_dossier_mec ("ID_DMC") ON DELETE CASCADE,
    "CONTEXTE" character varying(30) NOT NULL,
    "IM" character varying(20) NOT NULL,
    "DESIGNE_LE" timestamp without time zone NOT NULL,
    "DESIGNE_PAR" character varying(100),
    CONSTRAINT uq_cao_representant UNIQUE ("ID_DMC", "CONTEXTE"),
    CONSTRAINT ck_cao_representant_contexte CHECK ("CONTEXTE" IN ('SEANCE', 'SEANCE_FINANCIERE', 'RAPPORT', 'AMI'))
);

ALTER TABLE public.t_seance_financiere ADD COLUMN IF NOT EXISTS "SIGNATAIRES" character varying(1000);
ALTER TABLE public.t_seance_financiere ADD COLUMN IF NOT EXISTS "PV_SIGNE_LE" timestamp without time zone;

CREATE TABLE IF NOT EXISTS public.t_seance_financiere_signature (
    "ID" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ID_DMC" bigint NOT NULL,
    "RONDE" integer NOT NULL,
    "IM" character varying(20) NOT NULL,
    "DATE" timestamp without time zone NOT NULL,
    "EMPECHEMENT" boolean NOT NULL DEFAULT false,
    "MOTIF" text,
    "CONSTATE_PAR" character varying(100),
    CONSTRAINT uq_seance_financiere_signature UNIQUE ("ID_DMC", "RONDE", "IM"),
    CONSTRAINT fk_seance_financiere_signature FOREIGN KEY ("ID_DMC", "RONDE") REFERENCES public.t_seance_financiere ("ID_DMC", "RONDE") ON DELETE CASCADE
);
