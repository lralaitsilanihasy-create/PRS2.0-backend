-- 2. t_parametre_interne_procedure.CAO_QUORUM : la surcharge d'une procédure (même forme, nul = la règle globale).
-- 3. t_cao_representant : le représentant du président, désigné par lui pour un contexte (SEANCE, SEANCE_FINANCIERE, RAPPORT, AMI).
-- 4. t_seance_financiere : SIGNATAIRES (les présents appelés à signer le PV) et PV_SIGNE_LE ; t_seance_financiere_signature : les
--    signatures électroniques simples et les empêchements, sur le modèle de t_seance_signature.
