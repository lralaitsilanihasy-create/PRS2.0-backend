-- ═══════════════════════════════════════════════════════════════════════════════════════════════
-- V156 — La liste restreinte saisie de l'appel d'offres restreint (demande front du 2026-11-02 `demande-backend-2026-11-02-appel-
-- offres-restreint.md`, §B3 ; décret n° 2019-1310, art. 11-2 et 13 ; loi n° 2016-055, art. 38-II).
--
-- Par VERSION de fiche, comme le motif du recours (V155) : saisie en brouillon, figée à la validation, copiée à la révision ; exigée
-- au bilan d'une ligne en mode restreint (contrôle bloquant LISTE_RESTREINTE). La lettre LETTRE-AOR la reprend (plus de seconde
-- saisie des candidats à l'impression).
--
-- 1. t_fiche_liste_restreinte : la source de la liste (une ligne par version au plus).
-- 2. t_fiche_candidat_restreint : les candidats, dans l'ordre (le rang est la position) — au moins trois, contrôlé par le service.
-- Idempotente.
-- ═══════════════════════════════════════════════════════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS public.t_fiche_liste_restreinte (
    "ID_FICHE"   integer NOT NULL,
    "SOURCE"     character varying(30) NOT NULL,
    "SAISI_LE"   timestamp without time zone NOT NULL,
    "SAISI_PAR"  character varying(50),
    CONSTRAINT t_fiche_liste_restreinte_pkey PRIMARY KEY ("ID_FICHE"),
    CONSTRAINT fk_fiche_liste_restreinte_fiche FOREIGN KEY ("ID_FICHE") REFERENCES public.t_fiche_marche ("ID_FICHE") ON DELETE CASCADE,
    CONSTRAINT ck_fiche_liste_restreinte_source CHECK ("SOURCE" IN ('APPEL_CANDIDATURES', 'BASE_AUTORITE', 'PREMIER_APPEL_OFFRES',
                                                                     'REGISTRE_ARMP', 'ORGANISME_PROFESSIONNEL'))
);

CREATE TABLE IF NOT EXISTS public.t_fiche_candidat_restreint (
    "ID"           integer GENERATED BY DEFAULT AS IDENTITY,
    "ID_FICHE"     integer NOT NULL,
    "RANG"         integer NOT NULL,
    "NOM"          character varying(255) NOT NULL,
    "ADRESSE"      character varying(1000) NOT NULL,
    "EMAIL"        character varying(150),
    "ID_CANDIDAT"  character varying(10),
    "NIF"          character varying(30),
    CONSTRAINT t_fiche_candidat_restreint_pkey PRIMARY KEY ("ID"),
    CONSTRAINT fk_fiche_candidat_restreint_liste FOREIGN KEY ("ID_FICHE") REFERENCES public.t_fiche_liste_restreinte ("ID_FICHE")
        ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS ix_fiche_candidat_restreint_fiche ON public.t_fiche_candidat_restreint ("ID_FICHE", "RANG");
