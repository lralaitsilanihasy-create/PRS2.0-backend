-- V89 — Évaluation des offres, lot 3 (prestations intellectuelles), tranche PI-d2a (demande front du 2026-10-07,
-- `demande-backend-2026-10-07-evaluation-pi.md`, §B5, §B6 ; arbitrages du pilote du 2026-10-08 : dépenses remboursables saisies par
-- la commission, négociation conduite par la PRMP (ou son UGPM), échec motivé puis le suivant (Q7 en attente du juriste), séance
-- complémentaire pour ouvrir la financière du suivant quand seule celle du premier l'a été).
--
-- 1. t_evaluation_financiere : la saisie d'une proposition financière ouverte (prix lu, corrections, dépenses remboursables, refus).
-- 2. t_evaluation_classement_pi : l'arrêt du classement d'un lot par le président, son départage motivé, sa réouverture.
-- 3. t_negociation : les négociations successives d'un lot, une seule en cours, une seule réussie.
-- 4. t_seance_financiere : une ronde par séance (1 = la seconde séance, 2… = les séances complémentaires).
-- Idempotente.
-- ═══════════════════════════════════════════════════════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS public.t_evaluation_financiere (
    "ID"                  bigint GENERATED BY DEFAULT AS IDENTITY,
    "ID_DMC"              bigint NOT NULL,
    "ID_OFFRE"            character varying(36) NOT NULL,
    "LOT"                 integer,
    "PRIX_LU"             numeric(18,2) NOT NULL,
    "PRIX_LU_TTC"         numeric(18,2),
    "CORRECTIONS"         text,
    "PRIX_CORRIGE"        numeric(18,2) NOT NULL,
    "REMBOURSABLES"       numeric(18,2) NOT NULL DEFAULT 0,
    "MOTIF_REMBOURSABLES" text,
    "REFUS_MOTIF"         text,
    "REFUS_CLAUSE"        text,
    "PAR"                 character varying(100) NOT NULL,
    "LE"                  timestamp without time zone NOT NULL,
    CONSTRAINT t_evaluation_financiere_pkey PRIMARY KEY ("ID"),
    CONSTRAINT uk_evaluation_financiere_offre UNIQUE ("ID_OFFRE")
);
CREATE INDEX IF NOT EXISTS ix_evaluation_financiere_dmc ON public.t_evaluation_financiere ("ID_DMC");

CREATE TABLE IF NOT EXISTS public.t_evaluation_classement_pi (
    "ID_DMC"             bigint NOT NULL,
    "LOT"                integer NOT NULL,
    "ARRETE_LE"          timestamp without time zone,
    "ARRETE_PAR"         character varying(100),
    "OBSERVATION"        text,
    "ROUVERT_LE"         timestamp without time zone,
    "MOTIF_REOUVERTURE"  text,
    "DEPARTAGE"          text,
    "MOTIF_DEPARTAGE"    text,
    "DEPARTAGE_PAR"      character varying(100),
    "DEPARTAGE_LE"       timestamp without time zone,
    CONSTRAINT t_evaluation_classement_pi_pkey PRIMARY KEY ("ID_DMC", "LOT")
);

CREATE TABLE IF NOT EXISTS public.t_negociation (
    "ID"               bigint GENERATED BY DEFAULT AS IDENTITY,
    "ID_DMC"           bigint NOT NULL,
    "LOT"              integer NOT NULL,
    "ID_OFFRE"         character varying(36) NOT NULL,
    "ID_FINANCIERE"    character varying(36),
    "NUMERO"           integer,
    "RAISON_SOCIALE"   character varying(300),
    "RANG"             integer,
    "ETAT"             character varying(10) NOT NULL,
    "OUVERTE_LE"       timestamp without time zone NOT NULL,
    "OUVERTE_PAR"      character varying(100),
    "PREVUE_LE"        timestamp without time zone,
    "LIEU"             text,
    "CONCLUE_LE"       timestamp without time zone,
    "CONCLUE_PAR"      character varying(100),
    "DATE_NEGOCIATION" date,
    "TEXTE"            text,
    "MOTIF_ECHEC"      text,
    "PIECE"            bytea,
    "PIECE_NOM"        character varying(255),
    "PIECE_TYPE"       character varying(100),
    "PV"               bytea,
    "PV_DOCX"          bytea,
    CONSTRAINT t_negociation_pkey PRIMARY KEY ("ID"),
    CONSTRAINT ck_negociation_etat CHECK ("ETAT" IN ('EN_COURS', 'REUSSIE', 'ECHOUEE'))
);
CREATE INDEX IF NOT EXISTS ix_negociation_dmc ON public.t_negociation ("ID_DMC", "LOT");
-- Jamais deux négociations à la fois, jamais deux réussies, sur un même lot.
CREATE UNIQUE INDEX IF NOT EXISTS uk_negociation_en_cours ON public.t_negociation ("ID_DMC", "LOT") WHERE "ETAT" = 'EN_COURS';
CREATE UNIQUE INDEX IF NOT EXISTS uk_negociation_reussie ON public.t_negociation ("ID_DMC", "LOT") WHERE "ETAT" = 'REUSSIE';

ALTER TABLE public.t_seance_financiere ADD COLUMN IF NOT EXISTS "RONDE" integer NOT NULL DEFAULT 1;
ALTER TABLE public.t_seance_financiere ADD COLUMN IF NOT EXISTS "MOTIF" text;
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM information_schema.key_column_usage
                   WHERE table_schema = 'public' AND constraint_name = 't_seance_financiere_pkey' AND column_name = 'RONDE') THEN
        ALTER TABLE public.t_seance_financiere DROP CONSTRAINT IF EXISTS t_seance_financiere_pkey;
        ALTER TABLE public.t_seance_financiere ADD CONSTRAINT t_seance_financiere_pkey PRIMARY KEY ("ID_DMC", "RONDE");
    END IF;
END $$;
