-- V139 — Les modèles de PV construits dans l'application, lots P1-P2 (demande front du 2026-10-21
-- `demande-backend-2026-10-21-modele-pv-page.md` ; décision du pilote du 21/10 : option C').
--
-- Un modèle de PV n'est plus un Word déposé : c'est une page éditée dans l'application, enregistrée en document JSON aux types de
-- nœuds fermés (Q1), contrôlée et rendue en PDF par le serveur. Les versions Word déjà déposées (que des brouillons en recette)
-- restent en consultation et ne se mettent plus en vigueur (Q5).
--
-- 1. t_version_modele_pv : SUPPORT (WORD, PAGE) et DOCUMENT (le JSON) ; CONTENU et NOM_FICHIER ne valent que pour un Word.
--    EMPREINTE et TAILLE portent, pour une page, sur le JSON enregistré.
-- 2. t_image_modele_pv : les images des pages (PNG ou JPEG, 2 Mo au plus), contrôlées par leur contenu ; CODE nomme une image
--    fournie par l'application (EMBLEME : l'emblème des PV officiels).
-- ═══════════════════════════════════════════════════════════════════════════════════════════════

alter table public.t_version_modele_pv add column "SUPPORT" varchar(10) not null default 'WORD';
alter table public.t_version_modele_pv add column "DOCUMENT" text;
alter table public.t_version_modele_pv alter column "CONTENU" drop not null;
alter table public.t_version_modele_pv alter column "NOM_FICHIER" drop not null;
alter table public.t_version_modele_pv add constraint ck_version_modele_pv_support check (
    ("SUPPORT" = 'WORD' and "CONTENU" is not null and "NOM_FICHIER" is not null)
    or ("SUPPORT" = 'PAGE' and "DOCUMENT" is not null));

create table public.t_image_modele_pv (
    "ID_IMAGE"     bigint generated by default as identity primary key,
    "CODE"         varchar(30)   unique,
    "TYPE"         varchar(20)   not null check ("TYPE" in ('image/png', 'image/jpeg')),
    "CONTENU"      bytea         not null,
    "LARGEUR"      integer       not null,
    "HAUTEUR"      integer       not null,
    "TAILLE"       bigint        not null,
    "EMPREINTE"    varchar(64)   not null,
    "DEPOSEE_LE"   timestamp     not null,
    "DEPOSEE_PAR"  varchar(100)
);
