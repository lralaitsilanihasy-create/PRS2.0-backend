-- V138 — Le générateur de modèles de PV, lot G1 (demande front du 2026-10-20
-- `demande-backend-2026-10-20-generateur-modeles-pv.md` ; arbitrage du pilote : « fidèle au Word »).
--
-- L'Administrateur rédige un modèle de PV dans Word et le dépose ; l'application le contrôle, le versionne et le rattache aux
-- sous-types de dossier qu'il sert. Les fichiers sont en base (Q2) : ils survivent à une réinstallation du JAR et suivent la
-- sauvegarde de la base. Les conditions et les champs saisis se déclarent dans l'écran de la version (Q1), pas dans le Word.
--
-- 1. t_modele_pv : le modèle (code, libellé, nature PV ou LETTRE_RENVOI, actif ou archivé).
-- 2. t_version_modele_pv : ses versions, chacune avec son fichier, son empreinte et son rapport de contrôle (JSON) ; une seule
--    version EN_VIGUEUR par modèle ; une version en vigueur ne se modifie plus, on en dépose une nouvelle.
-- 3. t_condition_modele_pv, t_champ_saisi_modele_pv : déclarés par version.
-- 4. t_rattachement_modele_pv : un sous-type a au plus un modèle par nature (clé primaire). Pas de dates « du / au » :
--    le rattachement courant fait foi, son historique est au journal.
-- 5. t_journal_modele_pv : créé, déposé, déclaré, mis en vigueur, rattaché, dupliqué, archivé.
-- La production des PV par le générateur (PvGenere, B6) relève du lot G2 : rien ici ne change un PV existant.
-- ═══════════════════════════════════════════════════════════════════════════════════════════════

create table public.t_modele_pv (
    "ID_MODELE"        bigint generated by default as identity primary key,
    "CODE"             varchar(50)   not null unique,
    "LIBELLE"          varchar(255)  not null,
    "NATURE"           varchar(20)   not null check ("NATURE" in ('PV', 'LETTRE_RENVOI')),
    "ETAT"             varchar(20)   not null default 'ACTIF' check ("ETAT" in ('ACTIF', 'ARCHIVE')),
    "CREE_LE"          timestamp     not null,
    "CREE_PAR"         varchar(100),
    "ARCHIVE_LE"       timestamp,
    "MOTIF_ARCHIVAGE"  varchar(1000)
);

create table public.t_version_modele_pv (
    "ID_VERSION"      bigint generated by default as identity primary key,
    "ID_MODELE"       bigint        not null references public.t_modele_pv ("ID_MODELE"),
    "NUMERO"          integer       not null,
    "NOM_FICHIER"     varchar(255)  not null,
    "CONTENU"         bytea         not null,
    "EMPREINTE"       varchar(64)   not null,
    "TAILLE"          bigint        not null,
    "ETAT"            varchar(20)   not null check ("ETAT" in ('BROUILLON', 'EN_VIGUEUR', 'REMPLACEE')),
    "RAPPORT"         text,
    "BLOQUANT"        boolean       not null default true,
    "MOTIF"           varchar(1000),
    "DEPOSEE_LE"      timestamp     not null,
    "DEPOSEE_PAR"     varchar(100),
    "EN_VIGUEUR_LE"   timestamp,
    "EN_VIGUEUR_PAR"  varchar(100),
    "REMPLACEE_LE"    timestamp,
    constraint uk_version_modele_pv unique ("ID_MODELE", "NUMERO")
);

-- Une seule version en vigueur par modèle.
create unique index uk_version_modele_pv_en_vigueur on public.t_version_modele_pv ("ID_MODELE") where "ETAT" = 'EN_VIGUEUR';

create table public.t_condition_modele_pv (
    "ID_CONDITION"  bigint generated by default as identity primary key,
    "ID_VERSION"    bigint        not null references public.t_version_modele_pv ("ID_VERSION"),
    "NOM"           varchar(60)   not null,
    "EXPRESSION"    varchar(1000) not null,
    "LIBELLE"       varchar(255),
    "ORDRE"         integer       not null,
    constraint uk_condition_modele_pv unique ("ID_VERSION", "NOM")
);

create table public.t_champ_saisi_modele_pv (
    "ID_CHAMP"     bigint generated by default as identity primary key,
    "ID_VERSION"   bigint        not null references public.t_version_modele_pv ("ID_VERSION"),
    "CODE"         varchar(60)   not null,
    "LIBELLE"      varchar(255)  not null,
    "TYPE"         varchar(20)   not null check ("TYPE" in ('TEXTE', 'TEXTE_LONG', 'LISTE', 'CASE', 'DATE', 'NOMBRE', 'PIECE')),
    "OPTIONS"      text,
    "OBLIGATOIRE"  boolean       not null default false,
    "AIDE"         varchar(1000),
    "VISIBLE_SI"   varchar(60),
    "ORDRE"        integer       not null,
    constraint uk_champ_saisi_modele_pv unique ("ID_VERSION", "CODE")
);

create table public.t_rattachement_modele_pv (
    "ID_SOUS_TYPE"  varchar(20)   not null references public.tr_sous_type_dossier ("ID_SOUS_TYPE"),
    "NATURE"        varchar(20)   not null check ("NATURE" in ('PV', 'LETTRE_RENVOI')),
    "ID_MODELE"     bigint        not null references public.t_modele_pv ("ID_MODELE"),
    "RATTACHE_LE"   timestamp     not null,
    "RATTACHE_PAR"  varchar(100),
    primary key ("ID_SOUS_TYPE", "NATURE")
);

create table public.t_journal_modele_pv (
    "ID_JOURNAL"      bigint generated by default as identity primary key,
    "ID_MODELE"       bigint        not null references public.t_modele_pv ("ID_MODELE"),
    "NUMERO_VERSION"  integer,
    "ACTION"          varchar(30)   not null,
    "DETAIL"          varchar(2000),
    "PAR"             varchar(100),
    "LE"              timestamp     not null
);

create index ix_journal_modele_pv on public.t_journal_modele_pv ("ID_MODELE", "LE");
