-- 1. L'AMI d'une procédure de prestations intellectuelles (une fiche, un AMI) : critères de sélection pondérés, pièces attendues,
--    note minimale de qualification, nombre de candidats à retenir (six, art. 42-II), date limite, avis produit (PDF, Word), supports
--    de publication déclarés ; ou la dispense de publicité déclarée.
