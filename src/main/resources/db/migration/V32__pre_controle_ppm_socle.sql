-- (a) La FK vers tr_controleur d'abord : une PRMP n'y figure pas, l'écartement serait refusé en 23503.
--     Retrait par recherche dans le catalogue et non par nom en dur : « FK46sxegbovs81uk7h7bx7634hx »
--     est un nom engendré par Hibernate (V1, issu d'un pg_dump), qu'une base recréée autrement n'a pas.
DO $$
DECLARE nom text;
BEGIN
    SELECT con.conname INTO nom
    FROM pg_constraint con
    JOIN pg_class ref ON ref.oid = con.confrelid
    JOIN pg_class tab ON tab.oid = con.conrelid
    WHERE tab.relname = 't_anomalie' AND ref.relname = 'tr_controleur' AND con.contype = 'f'
    LIMIT 1;
    IF nom IS NOT NULL THEN
        EXECUTE format('ALTER TABLE public.t_anomalie DROP CONSTRAINT %I', nom);
    END IF;
END $$;

