CREATE TABLE IF NOT EXISTS public.t_anomalie_ligne (
    "ID_ANOMALIE" integer NOT NULL,
    "ID_DETAIL"   integer NOT NULL,
    "MONTANT"     numeric(38,2),
    CONSTRAINT t_anomalie_ligne_pkey PRIMARY KEY ("ID_ANOMALIE", "ID_DETAIL"),
    CONSTRAINT fk_anomalie_ligne_anomalie FOREIGN KEY ("ID_ANOMALIE")
        REFERENCES public.t_anomalie("ID_ANOMALIE") ON DELETE CASCADE,
    CONSTRAINT fk_anomalie_ligne_detail FOREIGN KEY ("ID_DETAIL")
        REFERENCES public.t_marche("ID_DETAIL") ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_anomalie_ligne_detail
    ON public.t_anomalie_ligne USING btree ("ID_DETAIL");

COMMENT ON TABLE public.t_anomalie_ligne IS
    'Lignes de marche visees par un signalement INTER-LIGNES (fractionnement : « ces trois lignes, '
    'compte X, cumul Y >= seuil Z »). MONTANT = montant en vigueur de la ligne au moment de la '
    'detection, garde pour que l''explication reste lisible apres modification du plan.';
