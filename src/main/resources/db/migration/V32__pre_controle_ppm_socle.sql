-- V32 — Pré-contrôle assisté du PPM (assistant IA, lot 3) : LE SOCLE DE DONNÉES.
--
-- Ce que le lot 3 demande (docs/plan-assistant-ia.md, §4, lot 3) : signaler à la PRMP les problèmes de
-- son PPM avant qu'elle ne soumette, et au contrôleur les points à regarder avant qu'il n'examine ;
-- chacun pouvant ÉCARTER un signalement en le motivant. Les règles détectent, l'IA explique (3.a).
-- Cette migration ne pose que les DONNÉES qui manquaient — aucune règle, aucun endpoint.
--
-- 1. tr_seuil_marche — LE RÉFÉRENTIEL DE SEUILS, NEUF, DATÉ ET ADMINISTRABLE.
--    t_seuil et t_regle_passation ont été supprimées le 2026-07-04 (c432e73) avec la détermination
--    automatique du mode : le PPM officiel ne porte pas de « situation » et le mode y est SAISI. Le
--    lot 3 ne revient pas sur cette décision — ce référentiel ne détermine ni ne bloque rien, il sert
--    UNIQUEMENT À SIGNALER. Sur le modèle d'AGPM_SEUIL_MONTANT : aucune valeur numérique dans le code.
--    Ses valeurs sont celles de l'arrêté n° 13 156/2019-MEF du 4 juillet 2019 (remis par le pilote), et
--    elles sont HORS TAXES — comme les montants estimatifs de PRS (arbitrage pilote du 2026-09-18) :
--    la comparaison est directe, sans conversion.
--    DATÉ, parce qu'un arrêté est remplacé : une valeur a une DATE_EFFET et, une fois remplacée, une
--    DATE_FIN. Le pré-contrôle d'un plan lit le barème en vigueur à sa date, pas le dernier saisi.
--
-- 2. t_marche.CATEGORIE_SEUIL — CE QUI MANQUAIT POUR CHOISIR UNE LIGNE DU BARÈME.
--    L'arrêté distingue quatre catégories de prestations (construction/réhabilitation de routes,
--    entretien routier, travaux non routiers, fournitures et services) ; PRS n'a que trois natures
--    (Travaux, Fournitures, Services). Impossible, avec la seule nature, de dire quel seuil s'applique
--    à un marché de travaux. La catégorie se pose donc SUR LA LIGNE. Elle reste facultative : une ligne
--    sans catégorie n'est pas en faute, elle est seulement moins précise — le moteur de règles évaluera
--    alors les catégories plausibles de sa nature et ne signalera que si elles divergent (3.e, fatigue
--    d'alerte).
--
-- 3. t_anomalie — LE SIGNALEMENT DEVIENT ÉCARTABLE PAR UNE PRMP.
--    La table du MLD portait déjà STATUT + COMMENTAIRE_TRAITEMENT : « écarter en motivant » était
--    modélisé. Mais IM_TRAITEMENT est un varchar(7) joint à tr_controleur, alors qu'un ID_PRMP fait 10
--    caractères : AUCUNE PRMP NE POUVAIT ÊTRE ENREGISTRÉE comme ayant écarté un signalement. C'est le
--    défaut C3 de l'audit du 2026-09-14, pour la troisième fois (V29 sur t_tache_dossier.IM_ACTEUR,
--    V31 sur t_session_utilisateur.IM_CONTROLEUR) : la colonne est élargie, la FK tombe, et un
--    TYPE_ACTEUR_TRAITEMENT dit de quel référentiel la référence vient — comme la claim acteurType du
--    jeton. GRAVITE passe de 10 à 20 caractères : « PRIORITAIRE » en fait 11.
--
-- 4. t_anomalie_ligne — LES SIGNALEMENTS INTER-LIGNES.
--    Le fractionnement illicite est le cœur du lot, et il ne concerne JAMAIS une ligne seule : « ces
--    trois lignes, compte X, cumul Y ≥ seuil Z ». ID_DETAIL (une ligne) ne peut pas le porter. La table
--    enfant liste les lignes visées ; ID_DETAIL reste réservé aux signalements d'une seule ligne.
--
-- CE QUI N'EST PAS ICI, ET C'EST DÉLIBÉRÉ :
--   * les RÈGLES (t_regle_anomalie) et le point de contrôle « fractionnement » de la grille
--     (tr_points_ctrl) sont des données de référentiel qui accompagnent le code des règles : elles
--     viendront avec lui, par un seeder idempotent au démarrage — tr_points_ctrl porte deux FK vers des
--     référentiels qu'aucune migration ne crée (voir l'encadré de V16) ;
--   * aucun seuil de PROCÉDURE n'est posé pour les prestations intellectuelles : l'arrêté n'en fixe
--     pas. Leur publicité relève du décret n° 2019-1310 (modifié par le décret n° 2022-1091) ; le
--     pilote a tranché le 2026-09-18 la seule valeur qui manquait — 100 000 000 Ar — et elle est semée
--     ci-dessous avec sa base légale, donc corrigeable sans redéploiement le jour où elle bouge.
--
-- Idempotente : CREATE TABLE / ADD COLUMN / CREATE INDEX IF NOT EXISTS, DROP CONSTRAINT dynamique,
-- semis borné par NOT EXISTS, et l'élargissement d'un varchar est une opération de métadonnées en
-- PostgreSQL (pas de réécriture de table), sans effet rejoué sur une colonne déjà élargie.
-- =====================================================================================================

